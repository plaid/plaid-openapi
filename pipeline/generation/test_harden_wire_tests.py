class InternalToolPortabilityTests(unittest.TestCase):
    def test_standard_library_tool_ignores_operator_module_toolchain(self):
        sources = {}
        for name, count in [('caller_test.go', 9), ('pager_test.go', 1), ('retrier_test.go', 5)]:
            text = 'package internal\nimport "example/core"\nfunc fixture() {\n'
            text += '_ = CallerParams{Client: client}\n' * count
            if name == 'retrier_test.go':
                text += 'clientParams.Client = server.Client()\n'
            sources[name] = text + '}\n'
        tool = Path(hardening.__file__).with_name('harden_internal_tests.go').resolve()
        with tempfile.TemporaryDirectory() as directory:
            Path(directory, 'go.mod').write_text('module example.invalid/operator\n\ngo 1.99.0\n')
            environment = hardening.internal_tool_environment()
            # Establish the original failure, without downloading another toolchain.
            baseline = dict(environment, GO111MODULE='on')
            failed = subprocess.run(['go', 'run', str(tool)], cwd=directory,
                                    input=json.dumps(sources), text=True, capture_output=True, env=baseline)
            self.assertNotEqual(failed.returncode, 0)
            self.assertIn('go.mod requires go >= 1.99.0', failed.stderr)
            result = subprocess.run(['go', 'run', str(tool)], cwd=directory,
                                    input=json.dumps(sources), text=True, capture_output=True, env=environment)
        self.assertEqual(result.returncode, 0, result.stderr)
        output = json.loads(result.stdout)
        self.assertEqual(sum(text.count('&core.CustomEndpointClient{') for text in output.values()), 16)


class WireTestHardeningTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.sdk = Path(self.temporary.name)
        (self.sdk / '.fern').mkdir()
        (self.sdk / '.fern/metadata.json').write_text(json.dumps(
            {'generatorName': 'fernapi/fern-go-sdk', 'generatorVersion': '1.70.3'}))
        (self.sdk / 'wiremock').mkdir()
        (self.sdk / 'wiremock/docker-compose.test.yml').write_text(hardening.COMPOSE_RAW)
        self.mappings = {'mappings': [
            {'request': {'urlPathTemplate': '/accounts/get', 'headers': {'PLAID-SECRET': {'matches': '.+'}},
                         'bodyPatterns': [{'equalToJson': {'access_token': 'fixture'}}]}, 'response': {'body': '{"ok":true}'}},
            {'request': {'urlPathTemplate': '/categories/get'}, 'response': {'body': '{}'}}], 'meta': {'total': 2}}
        (self.sdk / 'wiremock/wiremock-mappings.json').write_text(json.dumps(self.mappings, indent=2))
        for name in ('caller_test.go', 'pager_test.go', 'retrier_test.go'):
            (self.sdk / 'internal').mkdir(exist_ok=True)
            (self.sdk / 'internal' / name).write_text('internal fixture ' + name)
        self.source = ('// Code generated by Fern. DO NOT EDIT.\n\npackage example_test\n\n'
                       'func TestAccountsWithWireMock(\n\tt *testing.T,\n) {\n' + hardening.SETUP + hardening.RAW_AUTH +
                       '\trequest := "payload preserved"\n\t_ = request\n}\n'
                       'func TestCategoriesWithWireMock(\n\tt *testing.T,\n) {\n' + hardening.SETUP + hardening.RAW_NO_AUTH +
                       '\trequest := "payload preserved"\n\t_ = request\n}\n')
        self.test_path = self.sdk / 'example_test.go'
        self.test_path.write_text(self.source)
        # Go AST behavior has its own real tests; this boundary isolates Python preflight.
        self.tool = patch.object(hardening.subprocess, 'run', side_effect=lambda *args, **kwargs:
                                 subprocess.CompletedProcess(args, 0, kwargs['input'], ''))
        self.tool.start()
        self.addCleanup(self.tool.stop)

    def contents(self):
        return {str(p.relative_to(self.sdk)): p.read_bytes() for p in self.sdk.rglob('*') if p.is_file()}

    def test_all_clients_override_credentials_and_opt_in_with_canary_environment(self):
        with patch.dict(os.environ, {'PLAID_CLIENT_ID': 'ENV_ID_CANARY', 'PLAID_SECRET': 'ENV_SECRET_CANARY'}):
            result = hardening.harden(self.sdk)
        text = self.test_path.read_text()
        self.assertEqual(result['clients'], 2)
        self.assertEqual(text.count(hardening.HARDENED), 2)
        self.assertNotIn('WithBaseURL', text)
        self.assertNotIn('CANARY', text)
        self.assertEqual(hardening.BLOCK.sub('', self.source), hardening.BLOCK.sub('', text))
        mappings = json.loads((self.sdk / 'wiremock/wiremock-mappings.json').read_text())
        for mapping in mappings['mappings']:
            self.assertEqual(mapping['request']['headers']['PLAID-SECRET'], {'equalTo': 'wiremock-secret'})
            self.assertEqual(mapping['request']['headers']['PLAID-CLIENT-ID'], {'equalTo': 'wiremock-client-id'})
        old = copy.deepcopy(self.mappings)
        for data in (old, mappings):
            for mapping in data['mappings']:
                mapping['request'].pop('headers', None)
        self.assertEqual(old, mappings)
        self.assertEqual((self.sdk / 'wiremock/docker-compose.test.yml').read_text(), hardening.COMPOSE_HARDENED)
        before = self.contents()
        self.assertEqual(hardening.harden(self.sdk)['changed_files'], 0)
        self.assertEqual(hardening.harden(self.sdk, check=True)['changed_files'], 0)
        self.assertEqual(before, self.contents())

    def test_check_rejects_raw_generation_without_writing(self):
        before = self.contents()
        with self.assertRaisesRegex(hardening.HardeningError, 'hardening is missing'):
            hardening.harden(self.sdk, check=True)
        self.assertEqual(before, self.contents())

    def test_unknown_shapes_fail_before_any_file_changes(self):
        mutations = [
            (self.test_path, self.source.replace('option.WithSecret("test-value")', 'option.WithSecret(os.Getenv("PLAID_SECRET"))')),
            (self.test_path, self.source.replace('option.WithBaseURL', 'option.WithHTTPClient', 1)),
            (self.test_path, self.source + '\nfunc extra() { client.NewClient() }\n'),
            (self.sdk / 'wiremock/docker-compose.test.yml', hardening.COMPOSE_RAW.replace('"0:8080"', '"8080:8080"')),
            (self.sdk / 'wiremock/wiremock-mappings.json', json.dumps({'mappings': []})),
            (self.sdk / '.fern/metadata.json', '{"generatorName":"fernapi/fern-go-sdk","generatorVersion":"1.71.0"}'),
        ]
        original = self.contents()
        for path, content in mutations:
            with self.subTest(path=path):
                for name, data in original.items():
                    (self.sdk / name).write_bytes(data)
                path.write_text(content)
                before = self.contents()
                with self.assertRaises(hardening.HardeningError):
                    hardening.harden(self.sdk)
                self.assertEqual(before, self.contents())


