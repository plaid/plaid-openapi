#!/usr/bin/env python3
"""Apply Plaid's reviewed wire-test policy to pinned Fern Go output.

This deliberately accepts only the generator shapes we have reviewed. A generator
upgrade or a new constructor shape must be reviewed before tests can run or ship.
It never weakens the runtime destination check or reads developer credentials.
"""

import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys


class HardeningError(ValueError):
    pass


def require(condition, message):
    if not condition:
        raise HardeningError(message)


SETUP = ('\tWireMockBaseURL := os.Getenv("WIREMOCK_URL")\n'
         '\tif WireMockBaseURL == "" {\n'
         '\t\tWireMockBaseURL = "http://localhost:8080"\n\t}\n')
RAW = ('\tclient := client.NewClient(\n'
       '\t\toption.WithBaseURL(WireMockBaseURL),\n')
RAW_AUTH = RAW + '\t\toption.WithSecret("test-value"),\n\t)\n'
RAW_NO_AUTH = RAW + '\t)\n'
HARDENED = ('\twireMockClientID := "wiremock-client-id"\n'
            '\tclient := client.NewClient(\n'
            '\t\toption.WithCustomEndpoint(WireMockBaseURL, nil),\n'
            '\t\toption.WithClientID(&wireMockClientID),\n'
            '\t\toption.WithSecret("wiremock-secret"),\n\t)\n')
BLOCK = re.compile('|'.join(re.escape(SETUP + block)
                           for block in (HARDENED, RAW_AUTH, RAW_NO_AUTH)))
COMPOSE_RAW = '''services:
  wiremock:
    image: wiremock/wiremock:3.9.1
    ports:
      - "0:8080"
    volumes:
      - ./wiremock-mappings.json:/home/wiremock/mappings/wiremock-mappings.json
    command: ["--verbose"]
    healthcheck:
      test: ["CMD", "curl", "-f", "http://localhost:8080/__admin/health"]
      interval: 2s
      timeout: 5s
      retries: 15
      start_period: 5s
'''
COMPOSE_HARDENED = COMPOSE_RAW.replace('"0:8080"', '"127.0.0.1:0:8080"').replace(
    '    command: ["--verbose"]\n', '')


def transform_test(text, name):
    require(text.startswith('// Code generated by Fern. DO NOT EDIT.\n'),
            f'{name}: wire test is not recognized Fern output')
    tests = re.findall(r'^func (Test\w+WithWireMock)\(\n', text, re.MULTILINE)
    matches = list(BLOCK.finditer(text))
    require(tests and len(tests) == len(set(tests)) and len(matches) == len(tests),
            f'{name}: unrecognized wire-test setup or client options')
    remaining = BLOCK.sub('', text)
    require('WireMockBaseURL' not in remaining and 'client.NewClient(' not in remaining
            and 'wireMockClientID' not in remaining,
            f'{name}: unrecognized additional wire-test client')
    return BLOCK.sub(lambda _: SETUP + HARDENED, text), len(matches)


def internal_tool_environment():
    environment = {name: os.environ[name] for name in ('PATH', 'HOME', 'TMPDIR', 'GOCACHE', 'GOMODCACHE') if name in os.environ}
    # This tool imports only the standard library; ignore the operator's module.
    environment.update(GOWORK='off', GOENV='off', GOTOOLCHAIN='local', GO111MODULE='off', GOFLAGS='')
    return environment


def harden(sdk, *, check=False):
    sdk = Path(sdk)
    require(sdk.is_dir() and not sdk.is_symlink(), 'SDK must be a real directory')
    metadata_path = sdk / '.fern/metadata.json'
    require(metadata_path.is_file() and not metadata_path.is_symlink(), 'Missing regular Fern metadata')
    metadata = json.loads(metadata_path.read_text())
    require(metadata.get('generatorName') == 'fernapi/fern-go-sdk'
            and metadata.get('generatorVersion') == '1.70.3',
            'Review wire-test hardening before changing the pinned Fern Go generator')
    changes, files, clients = [], 0, 0
    for path in sorted(sdk.rglob('*_test.go')):
        require(not path.is_symlink(), f'{path}: refusing a symlinked test')
        if path == sdk / 'wire_test_security_test.go':
            continue  # Maintained policy test, preserved separately by .fernignore.
        text = path.read_text()
        if not any(marker in text for marker in ('WIREMOCK_URL', 'WithWireMock', 'WireMockBaseURL')):
            continue
        updated, count = transform_test(text, path.relative_to(sdk))
        files += 1
        clients += count
        if updated != text:
            changes.append((path, updated))
    require(files and clients, 'No recognized generated wire tests found')
    compose = sdk / 'wiremock/docker-compose.test.yml'
    require(compose.is_file() and not compose.is_symlink(), 'Missing regular WireMock compose file')
    compose_text = compose.read_text()
    require(compose_text in (COMPOSE_RAW, COMPOSE_HARDENED),
            'WireMock compose shape changed; review its bind address and logging before continuing')
    if compose_text != COMPOSE_HARDENED:
        changes.append((compose, COMPOSE_HARDENED))
    mappings_path = sdk / 'wiremock/wiremock-mappings.json'
    require(mappings_path.is_file() and not mappings_path.is_symlink(), 'Missing regular WireMock mappings')
    mappings_text = mappings_path.read_text()
    mappings = json.loads(mappings_text)
    require(set(mappings) == {'mappings', 'meta'} and mappings['meta'] == {'total': clients}
            and len(mappings['mappings']) == clients,
            'WireMock mapping inventory differs from generated clients')
    for mapping in mappings['mappings']:
        headers = mapping['request'].setdefault('headers', {})
        require(headers.get('PLAID-SECRET') in (None, {'matches': '.+'}, {'equalTo': 'wiremock-secret'})
                and headers.get('PLAID-CLIENT-ID') in (None, {'equalTo': 'wiremock-client-id'}),
                'WireMock credential expectations changed; review before continuing')
        headers['PLAID-SECRET'] = {'equalTo': 'wiremock-secret'}
        headers['PLAID-CLIENT-ID'] = {'equalTo': 'wiremock-client-id'}
    updated_mappings = json.dumps(mappings, indent=2, ensure_ascii=False) + ('\n' if mappings_text.endswith('\n') else '')
    if updated_mappings != mappings_text:
        changes.append((mappings_path, updated_mappings))
    internal_paths = {name: sdk / 'internal' / name for name in ('caller_test.go', 'pager_test.go', 'retrier_test.go')}
    require(all(path.is_file() and not path.is_symlink() for path in internal_paths.values()),
            'Missing regular generated internal tests')
    internal_sources = {name: path.read_text() for name, path in internal_paths.items()}
    transformed = subprocess.run(['go', 'run', str(Path(__file__).with_name('harden_internal_tests.go'))],
                                 input=json.dumps(internal_sources), text=True, capture_output=True,
                                 env=internal_tool_environment())
    require(transformed.returncode == 0, 'Internal test hardening failed: ' + transformed.stderr)
    internal_output = json.loads(transformed.stdout)
    require(internal_output.keys() == internal_sources.keys(), 'Unexpected internal test transformer output')
    for name, updated in internal_output.items():
        if updated != internal_sources[name]:
            changes.append((internal_paths[name], updated))
    # Validate the entire tree before changing any file, including the compose policy.
    require(not check or not changes, 'Wire-test hardening is missing; run harden_wire_tests.py --sdk PATH')
    for path, updated in changes:
        path.write_text(updated)
    return {'wire_test_files': files, 'clients': clients, 'internal_clients': 16, 'changed_files': len(changes)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sdk', type=Path, required=True)
    parser.add_argument('--check', action='store_true', help='Reject unhardened output without writing files')
    args = parser.parse_args()
    print(json.dumps(harden(args.sdk, check=args.check), sort_keys=True))


if __name__ == '__main__':
    try:
        main()
    except (HardeningError, OSError, ValueError) as error:
        sys.exit(str(error))
